#!/usr/bin/env python3
"""Check DevBacklog's package structure and local references with the standard library."""

import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit


SKILLS = (
    'planning-a-large-project',
    'executing-a-large-project',
    'reviewing-and-planning-tests',
)
PLANNING_FILES = (
    'scripts/ledger.py',
    'scripts/ledger_model.py',
    'scripts/ledger_checks.py',
    'scripts/ledger_storage.py',
    'scripts/hooks/pre-commit',
    'scripts/hooks/pre-push',
    'scripts/tests/test_checks.py',
    'scripts/tests/test_storage.py',
    'assets/templates/STATE.md',
    'assets/templates/PROTOCOL.md',
    'assets/templates/PLAN.md',
    'assets/templates/task.md',
    'assets/templates/prep-task.md',
    'assets/templates/checkpoint.md',
)


def validate(root):
    errors = []

    def require(condition, message):
        if not condition:
            errors.append(message)

    def read_manifest(relative):
        try:
            value = json.loads((root / relative).read_text(encoding='utf-8'))
            if not isinstance(value, dict):
                raise ValueError('expected a JSON object')
            return value
        except (OSError, ValueError) as error:
            errors.append(f'{relative}: {error}')
            return {}

    portable = read_manifest('plugin.json')
    codex = read_manifest('.codex-plugin/plugin.json')
    require(codex.get('name') == 'devbacklog', 'plugin name must be devbacklog')
    require(re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)',
                         str(codex.get('version', ''))), 'version must use X.Y.Z')
    for field in ('name', 'version', 'description', 'author', 'license'):
        require(bool(codex.get(field)) and portable.get(field) == codex.get(field),
                f'manifests must agree on nonempty {field}')
    require(codex.get('skills') == './skills', 'Codex skills must point to ./skills')
    extensions = portable.get('extensions', {})
    openai = extensions.get('com.openai', {}) if isinstance(extensions, dict) else {}
    portable_interface = openai.get('interface') if isinstance(openai, dict) else None
    interface = codex.get('interface')
    require(isinstance(interface, dict) and bool(interface) and interface == portable_interface,
            'manifests must agree on the interface')

    actual_skills = {path.name for path in (root / 'skills').glob('*') if path.is_dir()}
    require(actual_skills == set(SKILLS), 'package must contain exactly the three DevBacklog skills')
    for name in SKILLS:
        skill = root / 'skills' / name
        path = skill / 'SKILL.md'
        if not path.is_file():
            errors.append(f'missing skills/{name}/SKILL.md')
            continue
        text = path.read_text(encoding='utf-8')
        frontmatter = re.match(r'\A---\n(.*?)\n---\n', text, re.DOTALL)
        require(frontmatter is not None, f'{name}: missing YAML frontmatter')
        if frontmatter:
            require(f'name: {name}' in frontmatter[1].splitlines(), f'{name}: mismatched skill name')
            require(re.search(r'^description: \S.+$', frontmatter[1], re.MULTILINE),
                    f'{name}: missing description')
        require((skill / 'agents/openai.yaml').is_file(), f'{name}: missing agent metadata')

    for relative in PLANNING_FILES:
        require((root / 'skills' / SKILLS[0] / relative).is_file(),
                f'planning-a-large-project: missing {relative}')
    require((root / 'LICENSE').is_file(), 'missing LICENSE')
    require((root / 'README.md').is_file(), 'missing README.md')

    # Templates resolve against a generated ledger, which the CLI tests exercise.
    templates = root / 'skills' / SKILLS[0] / 'assets/templates'
    for path in root.rglob('*.md'):
        if path.is_relative_to(templates):
            continue
        for raw_target in re.findall(r'\[[^\]]*\]\(([^)\s]+)\)', path.read_text(encoding='utf-8')):
            target = urlsplit(raw_target)
            if target.scheme or target.netloc or not target.path:
                continue
            destination = (path.parent / unquote(target.path)).resolve()
            require(destination.is_relative_to(root) and destination.exists(),
                    f'{path.relative_to(root)}: missing or external local link {raw_target}')
    for path in root.rglob('*'):
        require(not path.is_symlink(), f'symlinks must be replaced with package files: {path.relative_to(root)}')
        require(path.name != '__pycache__' and path.suffix not in ('.pyc', '.pyo'),
                f'generated bytecode in package: {path.relative_to(root)}')
    return errors


def main():
    errors = validate(Path(__file__).resolve().parent.parent)
    print(json.dumps({'status': 'FAIL' if errors else 'PASS', 'skills': len(SKILLS),
                      'errors': errors, 'host_activation_tested': False}, indent=2))
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
